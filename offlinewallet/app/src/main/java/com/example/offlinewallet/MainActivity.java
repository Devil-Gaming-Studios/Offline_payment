    // Signs (publicKey + amount + timestamp) with the wallet's own private
    // key and posts it to the server. The server verifies that signature
    // before crediting anything — the local balance only updates once the
    // server confirms APPROVED (auto-approved under its limit, or after
    // /admin/topup/{id}/approve for larger amounts).
    private void requestTopUp(double amountRupees) {
        statusText.setText("Requesting top-up approval...");
        new Thread(() -> {
            try {
                long amountPaise = Math.round(amountRupees * 100);
                long timestamp = System.currentTimeMillis();
                byte[] pubKeyBytes = walletKeys.getPublic().getEncoded();

                java.nio.ByteBuffer buf = java.nio.ByteBuffer.allocate(pubKeyBytes.length + 8 + 8);
                buf.put(pubKeyBytes);
                buf.putLong(amountPaise);
                buf.putLong(timestamp);

                Signature signer = Signature.getInstance("Ed25519");
                signer.initSign(walletKeys.getPrivate());
                signer.update(buf.array());
                byte[] signature = signer.sign();

                JSONObject body = new JSONObject();
                body.put("publicKey", Base64.getEncoder().encodeToString(pubKeyBytes));
                body.put("amount", amountPaise);
                body.put("timestamp", timestamp);
                body.put("signature", Base64.getEncoder().encodeToString(signature));

                JSONObject result = postJson(SERVER_BASE_URL + "/topup/request", body);
                String status = result.optString("status", "UNKNOWN");
                String reason = result.optString("reason", "");
                String requestId = result.optString("requestId", "");

                if ("PENDING".equals(status)) {
                    runOnUiThread(() -> statusText.setText(
                            "Waiting for manual approval (id: " + requestId + ")..."));
                    pollForApproval(requestId, amountRupees);
                    return;
                }

                runOnUiThread(() -> {
                    if ("APPROVED".equals(status)) {
                        walletStore.credit(amountRupees);
                        walletStore.addHistoryEntry("Added money", amountRupees, "Top-up (server-approved)");
                        refreshBalance();
                        refreshHistory();
                        statusText.setText("Top-up approved: " + formatAmount(amountRupees));
                    } else {
                        statusText.setText("Top-up rejected: " + reason);
                    }
                });
            } catch (Exception e) {
                runOnUiThread(() -> statusText.setText("Top-up request failed: " + e.getMessage()));
            }
        }).start();
    }

    // Checks the server every few seconds to see whether an admin has
    // approved or rejected this request from the dashboard yet. Stops
    // after ~5 minutes if nobody actions it, or after too many consecutive
    // network failures in a row (a single dropped request no longer kills
    // the whole wait — only a run of them does).
    private void pollForApproval(String requestId, double amountRupees) {
        new Thread(() -> {
            int consecutiveFailures = 0;
            for (int attempt = 0; attempt < 100; attempt++) {
                try {
                    Thread.sleep(3000);

                    java.net.URL url = new java.net.URL(SERVER_BASE_URL + "/topup/" + requestId);
                    java.net.HttpURLConnection conn = (java.net.HttpURLConnection) url.openConnection();
                    conn.setRequestMethod("GET");
                    conn.setConnectTimeout(10000);
                    conn.setReadTimeout(10000);

                    StringBuilder sb = new StringBuilder();
                    try (java.io.BufferedReader reader = new java.io.BufferedReader(
                            new java.io.InputStreamReader(conn.getInputStream(), StandardCharsets.UTF_8))) {
                        String line;
                        while ((line = reader.readLine()) != null) sb.append(line);
                    }
                    JSONObject result = new JSONObject(sb.toString());
                    String status = result.optString("status", "PENDING");
                    consecutiveFailures = 0; // this attempt succeeded

                    if ("APPROVED".equals(status)) {
                        runOnUiThread(() -> {
                            walletStore.credit(amountRupees);
                            walletStore.addHistoryEntry("Added money", amountRupees, "Top-up (server-approved)");
                            refreshBalance();
                            refreshHistory();
                            statusText.setText("Top-up approved: " + formatAmount(amountRupees));
                        });
                        return;
                    } else if ("REJECTED".equals(status)) {
                        String reason = result.optString("reason", "");
                        runOnUiThread(() -> statusText.setText("Top-up rejected: " + reason));
                        return;
                    }
                    // still PENDING — keep polling
                } catch (Exception e) {
                    consecutiveFailures++;
                    if (consecutiveFailures >= 5) {
                        runOnUiThread(() -> statusText.setText(
                                "Lost connection while waiting for approval \u2014 check server/network"));
                        return;
                    }
                    // transient failure — just try again on the next tick
                }
            }
            runOnUiThread(() -> statusText.setText("Top-up still pending \u2014 check back later"));
        }).start();
    }

    private JSONObject postJson(String urlStr, JSONObject body) throws Exception {
        java.net.URL url = new java.net.URL(urlStr);
        java.net.HttpURLConnection conn = (java.net.HttpURLConnection) url.openConnection();
        conn.setRequestMethod("POST");
        conn.setRequestProperty("Content-Type", "application/json");
        conn.setDoOutput(true);
        conn.setConnectTimeout(10000);
        conn.setReadTimeout(10000);

        try (java.io.OutputStream os = conn.getOutputStream()) {
            os.write(body.toString().getBytes(StandardCharsets.UTF_8));
        }

        int code = conn.getResponseCode();
        java.io.InputStream is = code >= 200 && code < 300 ? conn.getInputStream() : conn.getErrorStream();
        StringBuilder sb = new StringBuilder();
        try (java.io.BufferedReader reader = new java.io.BufferedReader(
                new java.io.InputStreamReader(is, StandardCharsets.UTF_8))) {
            String line;
            while ((line = reader.readLine()) != null) sb.append(line);
        }
        return new JSONObject(sb.toString());
    }

