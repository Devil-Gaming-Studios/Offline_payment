    // Android 12+ (API 31+) requires these granted at RUNTIME, not just
    // declared in the manifest — the app will crash on BLE calls without this.
    private void requestBlePermissionsIfNeeded() {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
            String[] permissions = {
                    Manifest.permission.BLUETOOTH_SCAN,
                    Manifest.permission.BLUETOOTH_ADVERTISE,
                    Manifest.permission.BLUETOOTH_CONNECT,
                    Manifest.permission.CAMERA
            };
            boolean allGranted = true;
            for (String p : permissions) {
                if (ContextCompat.checkSelfPermission(this, p) != PackageManager.PERMISSION_GRANTED) {
                    allGranted = false;
                    break;
                }
            }
            if (!allGranted) {
                ActivityCompat.requestPermissions(this, permissions, PERMISSION_REQUEST_CODE);
            }
        }
    }

    private void startAdvertising() {
        byte[] pubKeyBytes = walletKeys.getPublic().getEncoded();
        gattServerManager = new BleGattServerManager(this, pubKeyBytes, this::handleIncomingPayload);
        gattServerManager.startAdvertisingAndServing();
        statusText.setText("Advertising \u2014 waiting for incoming payment...");
    }

    private void handleIncomingPayload(byte[] data) {
        try {
            String json = new String(data, StandardCharsets.UTF_8);
            JSONObject obj = new JSONObject(json);
            double amount = obj.getDouble("amount");
            String senderKey = obj.optString("senderKey", "unknown");

            walletStore.credit(amount);
            String counterparty = senderKey.length() > 12 ? senderKey.substring(0, 12) + "\u2026" : senderKey;
            walletStore.addHistoryEntry("Received", amount, counterparty);

            runOnUiThread(() -> {
                refreshBalance();
                refreshHistory();
                statusText.setText("Received " + formatAmount(amount));
            });
        } catch (JSONException e) {
            runOnUiThread(() -> statusText.setText("Received malformed payment data"));
        }
    }

    // expectedReceiverPublicKey: non-null when the recipient was identified via
    // QR scan — BleScanManager will refuse to pay any device whose identity
    // characteristic doesn't match this key. Null preserves the old "pay
    // whichever nearby device answers first" behavior.
    private void startScanAndSend(double amount, byte[] expectedReceiverPublicKey) {
        byte[] payload;
        try {
            JSONObject obj = new JSONObject();
            obj.put("amount", amount);
            obj.put("senderKey", Base64.getEncoder().encodeToString(walletKeys.getPublic().getEncoded()));
            obj.put("ts", System.currentTimeMillis());
            payload = obj.toString().getBytes(StandardCharsets.UTF_8);
        } catch (JSONException e) {
            Toast.makeText(this, "Failed to prepare payment", Toast.LENGTH_SHORT).show();
            return;
        }

        BleScanManager scanManager = new BleScanManager(this, payload, expectedReceiverPublicKey,
                new BleScanManager.OnSendCompleteListener() {
            @Override
            public void onSendSuccess() {
                walletStore.debit(pendingSendAmount);
                walletStore.addHistoryEntry("Sent", pendingSendAmount, "Nearby device");
                runOnUiThread(() -> {
                    refreshBalance();
                    refreshHistory();
                    statusText.setText("Sent successfully!");
                });
            }

            @Override
            public void onSendFailed(String reason) {
                runOnUiThread(() -> statusText.setText("Send failed: " + reason));
            }
        });
        scanManager.startScan();
        statusText.setText(expectedReceiverPublicKey != null
                ? "Connecting to scanned recipient..."
                : "Scanning for nearby wallets...");
    }

    private KeyPair loadOrGenerateKeys() throws Exception {
        File privFile = new File(getFilesDir(), "wallet_private.key");
        File pubFile  = new File(getFilesDir(), "wallet_public.key");

        if (privFile.exists() && pubFile.exists()) {
            byte[] privBytes = Files.readAllBytes(privFile.toPath());
            byte[] pubBytes  = Files.readAllBytes(pubFile.toPath());
            KeyFactory kf = KeyFactory.getInstance("Ed25519");
            PrivateKey priv = kf.generatePrivate(new PKCS8EncodedKeySpec(privBytes));
            PublicKey pub   = kf.generatePublic(new X509EncodedKeySpec(pubBytes));
            return new KeyPair(pub, priv);
        } else {
            KeyPairGenerator kpg = KeyPairGenerator.getInstance("Ed25519");
            KeyPair pair = kpg.generateKeyPair();
            Files.write(privFile.toPath(), pair.getPrivate().getEncoded());
            Files.write(pubFile.toPath(), pair.getPublic().getEncoded());
            return pair;
        }
    }
